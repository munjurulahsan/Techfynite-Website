// Writes src/data/imageSizes.ts: the intrinsic [width, height] of every raster image in
// public/images, so next/image can reserve the right space before an image loads.
// Run with `npm run images:sizes` after adding or replacing images.
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const imagesDir = path.join(root, "public", "images");
const outFile = path.join(root, "src", "data", "imageSizes.ts");

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.(png|jpe?g|webp)$/i.test(entry.name)) yield full;
  }
}

const sizes = {};
for await (const file of walk(imagesDir)) {
  const { width, height } = await sharp(file).metadata();
  const key = "/" + path.relative(path.join(root, "public"), file).split(path.sep).join("/");
  sizes[key] = [width, height];
}

const lines = [
  "// Generated by scripts/image-sizes.mjs: intrinsic [width, height] of each raster image.",
  "// Regenerate with `npm run images:sizes` after adding or replacing images.",
  "export const imageSizes: Record<string, [number, number]> = {",
  ...Object.keys(sizes)
    .sort()
    .map((k) => `  "${k}": [${sizes[k][0]}, ${sizes[k][1]}],`),
  "};",
  "",
  "export function sizeOf(src: string): { width: number; height: number } {",
  "  const [width, height] = imageSizes[src] ?? [1600, 1000];",
  "  return { width, height };",
  "}",
  "",
];

await writeFile(outFile, lines.join("\n"));
console.log(`Wrote ${Object.keys(sizes).length} image sizes to ${path.relative(root, outFile)}`);
